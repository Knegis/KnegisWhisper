"""Reproducible installed notices. Requires cargo-about 0.8.4 and a production Vite build."""
import argparse
import hashlib
import json
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "apps/desktop/src-tauri/resources/THIRD_PARTY_NOTICES.txt"

def normalized(text):
    return text.replace("\r\n", "\n").strip() + "\n"

def checked_sources(directory):
    sources = json.loads((directory / "sources.json").read_text(encoding="utf-8"))
    result = {}
    for item in sources:
        data = (directory / item["file"]).read_bytes()
        if hashlib.sha256(data).hexdigest() != item["sha256"]:
            raise ValueError("Changed notice source: " + item["file"])
        result[(item["name"], item.get("version"))] = (item, data.decode("utf-8"))
    return result

def render(rust, frontend):
    overrides = checked_sources(ROOT / "tools/licenses/overrides")
    blocks = ["Third-party notices\nGenerated by tools/licenses/generate.py.\n"
              "Includes the target desktop dependency graph (including build tooling), bundled interface modules, fonts and Silero VAD.\n"
              "Source links identify the distributed versions; no local paths or generation timestamps are included.\n"]
    packages = {}
    for crate in rust["crates"]:
        p = crate["package"]
        # Workspace code has its own bundled LICENSE. Vendored dependencies remain included.
        if not p["source"] and p["name"].startswith(("kw-", "knegiswhisper")):
            continue
        packages[(p["name"], p["version"])] = p
    for key, p in sorted(packages.items()):
        texts = []
        folder = Path(p["manifest_path"]).parent
        for entry in sorted(folder.iterdir()):
            if re.match(r"^(licen[cs]es?|copying|notice|copyright)([._-]|$)", entry.name, re.I):
                files = sorted(entry.rglob("*")) if entry.is_dir() else [entry]
                texts.extend(f.read_text(encoding="utf-8") for f in files if f.is_file())
        matched = [l for l in rust["licenses"] if any(
            (u["crate"]["name"], u["crate"]["version"]) == key for u in l["used_by"])]
        if key in overrides:
            item, value = overrides[key]
            texts.append("Notice source: " + item["url"] + "\n" + value)
        if not texts and not any(l["source_path"] for l in matched):
            raise ValueError("Missing original notice: " + repr(key))
        texts.extend(l["text"] for l in matched)
        if not texts:
            raise ValueError("Missing license text: " + repr(key))
        blocks.append(f"Rust: {key[0]} {key[1]}\nSource: {p.get('repository') or p['source']}\nLicense: {p['license']}\n"
                      + "\n".join(sorted(set(normalized(t) for t in texts))))
    for p in sorted(frontend, key=lambda x: (x["name"], x["version"])):
        if not p["texts"] or not all(t.strip() for t in p["texts"]):
            raise ValueError("Missing frontend license: " + p["name"])
        blocks.append(f"npm: {p['name']} {p['version']}\nSource: {p.get('source', '')}\nLicense: {p.get('license', '')}\n"
                      + "\n".join(normalized(t) for t in p["texts"]))
    for path in sorted((ROOT / "apps/desktop/src/fonts").glob("OFL-*.txt")):
        blocks.append("Bundled font: " + path.stem + "\n" + path.read_text(encoding="utf-8"))
    for item, content in checked_sources(ROOT / "tools/licenses/assets").values():
        model = ROOT / "apps/desktop/src-tauri/resources/ggml-silero-v5.1.2.bin"
        if hashlib.sha256(model.read_bytes()).hexdigest() != item["modelSha256"]:
            raise ValueError("Silero model changed; verify attribution again")
        blocks.append(item["name"] + "\nSource: " + item["url"] + "\nConversion: " + item["conversionSource"] + "\n" + content)
    return normalized("\n" + ("\n" + "=" * 78 + "\n").join(blocks))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cargo-about", default="cargo-about")
    parser.add_argument("--target", default="x86_64-pc-windows-msvc")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--rust-json", type=Path, help="Reuse a local cargo-about result for development only")
    args = parser.parse_args()
    if args.rust_json:
        rust = json.loads(args.rust_json.read_text(encoding="utf-8"))
    else:
        version = subprocess.check_output([args.cargo_about, "--version"], text=True).strip()
        if version != "cargo-about 0.8.4":
            raise ValueError("Expected cargo-about 0.8.4, got " + version)
        with tempfile.TemporaryDirectory() as temp:
            output = Path(temp) / "rust.json"
            subprocess.run([args.cargo_about, "generate", "--manifest-path",
                str(ROOT / "apps/desktop/src-tauri/Cargo.toml"), "--features", "tauri/custom-protocol",
                "--target", args.target, "--config", str(ROOT / "tools/licenses/about.toml"),
                "--locked", "--offline", "--fail", "--format", "json", "--output-file", str(output)], check=True, cwd=ROOT)
            rust = json.loads(output.read_text(encoding="utf-8"))
    frontend = json.loads((ROOT / "apps/desktop/.notice-build/dependency-notices.json").read_text(encoding="utf-8"))
    content = render(rust, frontend).encode("utf-8")
    if args.check:
        if OUTPUT.read_bytes() != content:
            raise SystemExit("Third-party notices are stale. Build the interface and run tools/licenses/generate.py.")
    else:
        OUTPUT.write_bytes(content)
    print(f"Notices {'checked' if args.check else 'generated'}: {len(content)} bytes")

if __name__ == "__main__":
    main()
